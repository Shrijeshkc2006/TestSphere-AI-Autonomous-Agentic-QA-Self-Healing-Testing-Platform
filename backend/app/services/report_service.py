def _ms_to_human(ms: Optional[int]) -> str:
    if ms is None:
        return "—"
    if ms < 1000:
        return f"{ms}ms"
    return f"{ms / 1000:.1f}s"


def generate_json_report(run_data: dict) -> str:
    """Serialize a run to JSON."""
    return json.dumps(run_data, indent=2, default=str)


def generate_html_report(run_data: dict) -> str:
    """Render an HTML report from run data dict."""
    env = Environment(loader=BaseLoader())
    template = env.from_string(_HTML_TEMPLATE)

    steps = []
    for sr in run_data.get("step_results", []):
        steps.append({
            "order": sr.get("order", ""),
            "title": sr.get("title", ""),
            "status": sr.get("status", ""),
            "duration": _ms_to_human(sr.get("duration_ms")),
            "error": sr.get("error_message", "") or "",
        })

    started = run_data.get("started_at")
    if isinstance(started, datetime):
        started_str = started.strftime("%Y-%m-%d %H:%M:%S UTC")
    else:
        started_str = str(started or "—")

    return template.render(
        run_id=run_data.get("id", ""),
        status=run_data.get("status", "").upper(),
        started_at=started_str,
        duration=_ms_to_human(run_data.get("duration_ms")),
        total_steps=run_data.get("total_steps", 0),
        passed_steps=run_data.get("passed_steps", 0),
        failed_steps=run_data.get("failed_steps", 0),
        healed_steps=run_data.get("healed_steps", 0),
        steps=steps,
        generated_at=datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M:%S UTC"),
    )


def generate_junit_report(run_data: dict) -> str:
    """Generate a JUnit XML report."""
    try:
        from junitparser import JUnitXml, TestSuite, TestCase, Failure, Skipped
        suite = TestSuite(run_data.get("id", "run"))
        suite.timestamp = str(run_data.get("started_at", ""))

        for sr in run_data.get("step_results", []):
            case = TestCase(name=sr.get("title", "step"), classname="TestSphere")
            dur = sr.get("duration_ms")
            if dur is not None:
                case.time = dur / 1000

            status = sr.get("status", "")
            if status == "failed":
                f = Failure(sr.get("error_message", "Step failed"))
                case.result = [f]
            elif status == "skipped":
                case.result = [Skipped()]

            suite.add_testcase(case)

        xml = JUnitXml()
        xml.add_testsuite(suite)
        return xml.tostring().decode()
    except ImportError:
        log.warning("report_service.junitparser_unavailable")
        return f'<?xml version="1.0"?><testsuites><testsuite name="{run_data.get("id", "run")}" tests="{run_data.get("total_steps", 0)}" failures="{run_data.get("failed_steps", 0)}"/></testsuites>'


async def save_reports(run_data: dict, artifact_dir: str, run_id: str) -> dict:
    """Generate and save all report formats. Returns paths."""
    base = Path(artifact_dir) / run_id
    base.mkdir(parents=True, exist_ok=True)

    paths = {}
    try:
        html = generate_html_report(run_data)
        html_path = base / "report.html"
        html_path.write_text(html, encoding="utf-8")
        paths["html"] = str(html_path)
    except Exception as e:
        log.error("report_service.html_failed", error=str(e))

    try:
        junit = generate_junit_report(run_data)
        junit_path = base / "report.xml"
        junit_path.write_text(junit, encoding="utf-8")
        paths["junit"] = str(junit_path)
    except Exception as e:
        log.error("report_service.junit_failed", error=str(e))

    try:
        js = generate_json_report(run_data)
        json_path = base / "report.json"
        json_path.write_text(js, encoding="utf-8")
        paths["json"] = str(json_path)
    except Exception as e:
        log.error("report_service.json_failed", error=str(e))

    return paths
